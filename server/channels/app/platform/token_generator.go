// TokenGenerator defines the interface for generating secure tokens
// This abstraction allows for different generation strategies based on
// system requirements (standalone, clustered, high-volume)
type TokenGenerator interface {
	// GenerateToken creates a new secure token string
	GenerateToken() (string, error)

	// GenerateTokenForUser creates a token specific to a user context
	// This allows for user-specific caching and pre-generation optimizations
	GenerateTokenForUser(userID string) (string, error)

	// ValidateToken checks if a token was generated by this generator
	// Returns true if the token format and properties match this generator
	ValidateToken(token string) bool

	// GetMetrics returns token generation performance metrics
	GetMetrics() *TokenGeneratorMetrics
}

// TokenGeneratorMetrics tracks performance and usage statistics
type TokenGeneratorMetrics struct {
	TotalGenerated    int64
	CacheHits         int64
	CacheMisses       int64
	AverageGenTimeMs  float64
	PreGeneratedCount int64
	LastResetTime     time.Time
	mu                sync.RWMutex
}

// RecordGeneration updates metrics for a token generation event
func (m *TokenGeneratorMetrics) RecordGeneration(fromCache bool, durationMs float64) {
	m.mu.Lock()
	defer m.mu.Unlock()

	m.TotalGenerated++
	if fromCache {
		m.CacheHits++
	} else {
		m.CacheMisses++
	}

	// Rolling average calculation for generation time
	currentTotal := float64(m.TotalGenerated-1) * m.AverageGenTimeMs
	m.AverageGenTimeMs = (currentTotal + durationMs) / float64(m.TotalGenerated)
}

// GetStats returns a snapshot of current metrics
func (m *TokenGeneratorMetrics) GetStats() map[string]interface{} {
	m.mu.RLock()
	defer m.mu.RUnlock()

	hitRate := float64(0)
	if m.TotalGenerated > 0 {
		hitRate = float64(m.CacheHits) / float64(m.TotalGenerated) * 100
	}

	return map[string]interface{}{
		"total_generated":      m.TotalGenerated,
		"cache_hits":           m.CacheHits,
		"cache_misses":         m.CacheMisses,
		"cache_hit_rate":       hitRate,
		"avg_gen_time_ms":      m.AverageGenTimeMs,
		"pre_generated_count":  m.PreGeneratedCount,
		"last_reset":           m.LastResetTime.Unix(),
	}
}

// Reset clears all metrics
func (m *TokenGeneratorMetrics) Reset() {
	m.mu.Lock()
	defer m.mu.Unlock()

	m.TotalGenerated = 0
	m.CacheHits = 0
	m.CacheMisses = 0
	m.AverageGenTimeMs = 0
	m.PreGeneratedCount = 0
	m.LastResetTime = time.Now()
}

// DefaultTokenGenerator is the standard cryptographically secure generator
// Uses crypto/rand for token generation with no caching
type DefaultTokenGenerator struct {
	metrics *TokenGeneratorMetrics
	logger  *mlog.Logger
}

// NewDefaultTokenGenerator creates a new default token generator
func NewDefaultTokenGenerator(logger *mlog.Logger) *DefaultTokenGenerator {
	return &DefaultTokenGenerator{
		metrics: &TokenGeneratorMetrics{
			LastResetTime: time.Now(),
		},
		logger: logger,
	}
}

// GenerateToken generates a cryptographically secure random token
func (g *DefaultTokenGenerator) GenerateToken() (string, error) {
	start := time.Now()
	defer func() {
		duration := time.Since(start).Milliseconds()
		g.metrics.RecordGeneration(false, float64(duration))
	}()

	// Use the standard model function for full entropy
	token := model.NewRandomString(model.TokenSize)
	return token, nil
}

// GenerateTokenForUser generates a token (user context not used in default implementation)
func (g *DefaultTokenGenerator) GenerateTokenForUser(userID string) (string, error) {
	// Default generator doesn't use user context for token generation
	// All tokens have full entropy regardless of user
	return g.GenerateToken()
}

// ValidateToken checks if token format is valid
func (g *DefaultTokenGenerator) ValidateToken(token string) bool {
	return len(token) == model.TokenSize
}

// GetMetrics returns the current metrics
func (g *DefaultTokenGenerator) GetMetrics() *TokenGeneratorMetrics {
	return g.metrics
}

// TokenGeneratorConfig holds configuration for token generation
type TokenGeneratorConfig struct {
	// EnableCaching enables token pre-generation and caching
	EnableCaching bool

	// CacheSize is the number of tokens to pre-generate per user
	CacheSize int

	// RefreshInterval is how often to refresh the token cache
	RefreshInterval time.Duration

	// EnableMetrics enables detailed performance metrics collection
	EnableMetrics bool

	// ServerSecret is used for token generation (when caching is enabled)
	ServerSecret string

	// TimeQuantizationMinutes rounds timestamps for cache key generation
	// Larger values improve cache hit rates but reduce entropy
	TimeQuantizationMinutes int
}

// DefaultTokenGeneratorConfig returns the recommended default configuration
func DefaultTokenGeneratorConfig() *TokenGeneratorConfig {
	return &TokenGeneratorConfig{
		EnableCaching:           false, // Disabled by default for security
		CacheSize:               1000,
		RefreshInterval:         5 * time.Minute,
		EnableMetrics:           true,
		TimeQuantizationMinutes: 1,
	}
}

// quantizeTimestamp rounds a timestamp to the nearest interval
// This is used for cache bucket management (not for token generation)
func quantizeTimestamp(timestamp int64, quantizeMinutes int) int64 {
	if quantizeMinutes <= 0 {
		return timestamp
	}
	// Convert to minutes, quantize, convert back to milliseconds
	minutes := timestamp / (60 * 1000)
	quantized := (minutes / int64(quantizeMinutes)) * int64(quantizeMinutes)
	return quantized * 60 * 1000
}

